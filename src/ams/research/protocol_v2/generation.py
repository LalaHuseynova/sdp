"""Protocol v2, plan.md step 1.3: specs, requests and strict parsers for generated data.

Fresh held-out attacks and benign documents are generated by Claude Sonnet (owner
decision 2) through the guarded `v2_generation` scope. This module is offline: it
builds deterministic per-request SPECS, the exact REQUESTS, and PARSERS that apply
exclusion rule E1 with a reason code. Later rules (E2-E4, I1) live in
`inclusion.py` (step 1.4).

Leakage guard: prompts carry only label DEFINITIONS written for this protocol
(below); no MPBench case text ever enters a generation prompt. Quotas follow the
label distribution of the 102 MPBench cases that can serve as scored attacks
("reachable"), computed from the repository's frozen inputs and recorded in the
manifest, with an equal number of attacks per domain.
"""

